export function formatCount(n: number): string {
  const v = Math.round(n);
  if (v < 10000) return String(v);
  if (v < 1_000_000) return `${(v / 1000).toFixed(v < 100000 ? 1 : 0)}K`;
  return `${(v / 1_000_000).toFixed(1)}M`;
}
